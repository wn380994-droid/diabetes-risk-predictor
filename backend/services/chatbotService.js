const OpenAI = require('openai');

const client = new OpenAI({
  apiKey: process.env.OPENROUTER_API_KEY,
  baseURL: 'https://openrouter.ai/api/v1'
});

// ⭐ မြန်မာလို System Prompt အစစ်
const SYSTEM_PROMPT = `သင်သည် ဆီးချိုရောဂါဆိုင်ရာ အထူးပြု AI လက်ထောက်တစ်ဦးဖြစ်သည်။ သင့်နာမည်က "ဆီးချိုအကူအညီ" ဖြစ်သည်။

【သင့်တာဝန်များ】
၁။ ဆီးချိုရောဂါ (Diabetes) နှင့် ပတ်သက်သော မေးခွန်းများကိုသာ ဖြေကြားပါ။
၂။ ဆီးချိုရောဂါ အမျိုးအစား ၁၊ အမျိုးအစား ၂၊ ကိုယ်ဝန်ဆောင်ဆီးချို အကြောင်း ရှင်းပြနိုင်သည်။
၃။ ဆီးချိုရောဂါ၏ လက္ခဏာများ၊ နောက်ဆက်တွဲဆိုးကျိုးများ၊ ကာကွယ်နည်းများ၊ ကုသနည်းများ အကြောင်း ဖြေနိုင်သည်။
၄။ သွေးတွင်းသကြားဓာတ် (Glucose)၊ HbA1c၊ အင်ဆူလင်၊ BMI စတဲ့ အညွှန်းကိန်းများ အကြောင်း ရှင်းပြနိုင်သည်။
၅။ ဆီးချိုရောဂါအတွက် သင့်တော်သော အစားအသောက်၊ လေ့ကျင့်ခန်း၊ နေထိုင်မှုပုံစံ အကြံပြုချက်များ ပေးနိုင်သည်။

【တင်းကျပ်သော စည်းမျဉ်းများ】
- မြန်မာဘာသာဖြင့်သာ ဖြေကြားပါ။
- ဆီးချိုရောဂါနှင့် မသက်ဆိုင်သော မေးခွန်းများ (နိုင်ငံရေး၊ စစ်ရေး၊ အားကစား၊ နည်းပညာ၊ ခရီးသွား စသည်) ကို "ကျွန်ုပ်သည် ဆီးချိုရောဂါဆိုင်ရာ မေးခွန်းများကိုသာ ဖြေကြားပေးနိုင်ပါသည်။ ဆီးချိုရောဂါနှင့် ပတ်သက်သော မေးခွန်းများ မေးမြန်းပေးပါ။" လို့ ယဉ်ကျေးစွာ ပြန်ဖြေပါ။
- ဆေးဘက်ဆိုင်ရာ အကြံဉာဏ် ပေးတဲ့အခါ "ဤအချက်အလက်သည် ယေဘုယျသတင်းအချက်အလက်သာဖြစ်ပြီး ဆေးဘက်ဆိုင်ရာ အကြံဉာဏ်အဖြစ် မယူဆပါရန်။ တိကျသော ရောဂါရှာဖွေမှုနှင့် ကုသမှုအတွက် ဆရာဝန်နှင့် တိုင်ပင်ပါ။" လို့ အမြဲ ထည့်ပြောပါ။
- သင်သည် ဆရာဝန် မဟုတ်ကြောင်း ရှင်းလင်းစွာ ပြောပါ။
- ဆေးဝါးအမည်များ တိတိကျကျ ညွှန်ကြားခြင်း မပြုလုပ်ပါနှင့်။

【ဖြေကြားပုံစံ】
- ရိုးရှင်းပြီး နားလည်လွယ်သော စကားဖြင့် ဖြေပါ။
- ခေါင်းစဉ်တွေ၊ အမှတ်စဉ်တွေ သုံးပြီး ဖတ်ရလွယ်အောင် စီစဉ်ပါ။
- လိုအပ်ရင် ဥပမာများ ထည့်ပြောပါ။

【ဥပမာ မေးခွန်းများ】
- "ဆီးချိုရောဂါ လက္ခဏာတွေက ဘာလဲ"
- "သွေးတွင်းသကြားဓာတ် ဘယ်လောက်ရှိရင် ဆီးချိုလို့ ခေါ်လဲ"
- "ဆီးချိုရောဂါ ကာကွယ်ဖို့ ဘာစားသင့်လဲ"
- "HbA1c ဆိုတာ ဘာလဲ"`;

const getChatbotResponse = async (userMessage) => {
  try {
    console.log('📤 OpenRouter API ကို ခေါ်နေသည်...');
    console.log('📝 User Message:', userMessage);
    
    const completion = await client.chat.completions.create({
      model: 'openrouter/free',  
      messages: [
        { role: 'system', content: SYSTEM_PROMPT },
        { role: 'user', content: userMessage }
      ],
      temperature: 0.5,      // ← ပိုတည်ငြိမ်အောင် 0.7 → 0.5
      max_tokens: 1024,
    });

    const text = completion.choices[0]?.message?.content || '';
    console.log('✅ OpenRouter ရလဒ် ရပါပြီ');

    return { success: true, message: text };
    
  } catch (error) {
    console.error('❌ Chatbot Error:', error.message);
    
    return {
      success: false,
      message: 'တောင်းပန်ပါတယ်၊ ကျွန်ုပ် ယခုအချိန်တွင် ဖြေကြားနိုင်ခြင်း မရှိပါ။ ခဏနေရင် ပြန်ကြိုးစားကြည့်ပါ။'
    };
  }
};

module.exports = { getChatbotResponse };